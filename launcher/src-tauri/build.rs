use std::path::{Path, PathBuf};

fn main() {
    modtopia();
    tauri_build::build()
}

/// The Modtopia core (runtime/third_party/modtopia: C11, vendored unchanged, MIT), compiled into the launcher for its Mods page
/// (modtopia_ffi.rs), and its mappings embedded as `$OUT_DIR/modtopia_mappings.rs` (MAPPINGS: file name and bytes, one row a file),
/// which mods.rs writes into the game folder. The runtime builds the same files with its own CMake.
fn modtopia() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../runtime/third_party/modtopia");
    let src = root.join("core/src");
    let mut build = cc::Build::new();
    for name in ["mt_util", "mt_toml", "mt_version", "mt_zip", "mt_manifest", "mt_loader", "mt_runtime", "mt_patch", "mt_net", "mt_png"] {
        build.file(src.join(format!("{name}.c")));
    }
    build.include(root.join("sdk/include")).define("_CRT_SECURE_NO_WARNINGS", None).warnings(false);
    if build.get_compiler().is_like_msvc() {
        // the dispatch table uses <stdatomic.h>, which cl compiles only with this switch
        build.flag("/std:c11").flag("/experimental:c11atomics");
    } else {
        build.flag("-std=gnu11"); // POSIX (dirent, fseeko, dlopen) next to C11
    }
    build.compile("modtopia");
    println!("cargo:rerun-if-changed={}", src.display());
    println!("cargo:rerun-if-changed={}", root.join("sdk/include").display());

    let maps = root.join("mappings");
    println!("cargo:rerun-if-changed={}", maps.display());
    let mut files: Vec<PathBuf> = std::fs::read_dir(&maps)
        .expect("runtime/third_party/modtopia/mappings")
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "toml"))
        .collect();
    files.sort();
    let rows: String = files
        .iter()
        .map(|p| {
            println!("cargo:rerun-if-changed={}", p.display());
            let abs = p.canonicalize().unwrap_or_else(|_| p.clone());
            format!("    ({:?}, include_bytes!({:?})),\n", p.file_name().unwrap().to_string_lossy(), abs.to_string_lossy())
        })
        .collect();
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("modtopia_mappings.rs");
    std::fs::write(out, format!("/// Generated by build.rs from runtime/third_party/modtopia/mappings/*.toml.\npub const MAPPINGS: &[(&str, &[u8])] = &[\n{rows}];\n")).unwrap();
}
